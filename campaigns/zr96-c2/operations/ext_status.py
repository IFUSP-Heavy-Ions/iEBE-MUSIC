#!/usr/bin/env python3
"""Write the analysis-facing status table for the design_2001-2360 extension.

The analysis session reads this to know which points are ready, so it has to be
generated rather than hand-kept: one row per label with jobs merged, ok events,
and a note for anything outside the campaign baselines (handoff section 5).

Also flags the three conditions the handoff says to report rather than work
around: fewer than 90 merged jobs, an ok fraction well below the baseline, and
any nonzero seed_add or unexpected status value.

Usage: python3 campaigns/zr96-c2/operations/ext_status.py [--first 2001] [--last 2360]
"""
import argparse
import csv
import glob
import io
import os
import re
import tarfile

MERGED = '/data/mluzum/zr96c2_results/merged'
GROUPS = ('/data/mluzum/zr96c2_results/analysis/design/'
          'candidate_A96_c2_ext_groups.csv')
OUT = '/data/mluzum/zr96c2_results/prod/STATUS_A96_c2_ext.md'
EXPECTED_JOBS = 100
OK_BASELINE_MEDIAN = 1917      # handoff section 5, from 616 original points
OK_BASELINE_P5 = 1772


def point_row(label, dp):
    mdir = os.path.join(MERGED, dp)
    h5 = os.path.join(mdir, dp + '.h5')
    merged = os.path.exists(h5)
    jobs_merged = 0
    src = os.path.join(mdir, 'sources.txt')
    if os.path.exists(src):
        m = re.search(r'tars=(\d+)', open(src).read())
        if m:
            jobs_merged = int(m.group(1))
    events = ok = other = seed_nonzero = 0
    statuses = {}
    csvtgz = os.path.join(mdir, 'csv.tgz')
    if os.path.exists(csvtgz):
        try:
            with tarfile.open(csvtgz, 'r:gz') as t:
                for mem in t.getmembers():
                    if not mem.name.endswith('.csv'):
                        continue
                    data = t.extractfile(mem).read().decode()
                    for r in csv.DictReader(io.StringIO(data)):
                        events += 1
                        st = r.get('status', '')
                        statuses[st] = statuses.get(st, 0) + 1
                        if st == 'ok':
                            ok += 1
                        else:
                            other += 1
                        try:
                            if float(r.get('seed_add', 0)) != 0.0:
                                seed_nonzero += 1
                        except ValueError:
                            pass
        except (tarfile.TarError, OSError):
            pass
    notes = []
    if merged and jobs_merged < 90:
        notes.append('only %d merged jobs' % jobs_merged)
    if merged and ok and ok < OK_BASELINE_P5:
        notes.append('ok=%d below baseline p5 (%d)' % (ok, OK_BASELINE_P5))
    if seed_nonzero:
        notes.append('seed_add nonzero on %d events' % seed_nonzero)
    unexpected = {k: v for k, v in statuses.items()
                  if k not in ('ok', 'no_collision', 'no_trento')}
    if unexpected:
        notes.append('unexpected status %s' % unexpected)
    state = 'merged' if merged else ('no h5' if jobs_merged == 0 else 'partial')
    return (label, dp, state, jobs_merged, EXPECTED_JOBS, events, ok, other,
            '; '.join(notes) or '-')


def group_map(path):
    out = {}
    if os.path.exists(path):
        for r in csv.DictReader(open(path)):
            out[r['label']] = (r['component'], r['medium_group'])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--first', type=int, default=2001)
    ap.add_argument('--last', type=int, default=2360)
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()

    gm = group_map(GROUPS)
    rows = []
    for i in range(args.first, args.last + 1):
        label = 'design_%04d' % i
        rows.append(point_row(label, 'dp%04d' % i))

    merged_n = sum(1 for r in rows if r[2] == 'merged')
    flagged = [r for r in rows if r[8] != '-']
    lines = [
        '# STATUS: zr96c2 design_%04d-%04d (A=96 extension)' %
        (args.first, args.last), '',
        'Generated by `campaigns/zr96-c2/operations/ext_status.py`. One row per point; the analysis '
        'session reads this to know which points are ready.', '',
        '## Summary', '',
        '| points | merged | partial | not started | flagged |',
        '|---|---|---|---|---|',
        '| %d | %d | %d | %d | %d |' %
        (len(rows), merged_n,
         sum(1 for r in rows if r[2] == 'partial'),
         sum(1 for r in rows if r[2] == 'no h5'), len(flagged)), '',
        'Baselines from the 616 merged original points: median 1917 ok events, '
        'p5 1772, median 100 merged jobs. Flags: fewer than 90 merged jobs, ok '
        'below 1772, nonzero seed_add, unexpected status.', '',
        '## Per point', '',
        '| label | dp | state | jobs merged | events | ok | other | component | '
        'pair | notes |',
        '|---|---|---|---|---|---|---|---|---|---|',
    ]
    for label, dp, state, jm, exp, ev, ok, other, notes in rows:
        comp, pair = gm.get(label, ('-', '-'))
        lines.append('| %s | %s | %s | %d/%d | %d | %d | %d | %s | %s | %s |' %
                     (label, dp, state, jm, exp, ev, ok, other, comp, pair,
                      notes))
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (%d rows, %d merged, %d flagged)' %
          (args.out, len(rows), merged_n, len(flagged)))


if __name__ == '__main__':
    main()
