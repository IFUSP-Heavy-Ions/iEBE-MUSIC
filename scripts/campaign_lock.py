#!/usr/bin/env python3
"""Write the software lock of a campaign: every revision that went into its image.

A container image is built by one commit's docker/Dockerfile, which fetches the
framework at a pinned commit, whose codes/get_code_packages.sh in turn
clones every physics code at a pinned commit and applies the patches in
codes/patches/.  This script walks that chain *in git* (nothing is built or
downloaded) and writes it down as one YAML file, so a campaign record can say
exactly which sources its binaries were compiled from.

    python3 scripts/campaign_lock.py --dockerfile-commit 06cc504 \\
        > campaigns/zr96-c2/components.lock.yaml

--dockerfile-commit is the commit whose docker/Dockerfile built the image.  The
framework revision is read out of that Dockerfile; everything else is read out
of the framework revision.
"""

import argparse
import hashlib
import re
import subprocess
import sys


def git(*args):
    return subprocess.run(("git", ) + args,
                          check=True,
                          capture_output=True,
                          text=True).stdout


def git_bytes(*args):
    return subprocess.run(("git", ) + args, check=True,
                          capture_output=True).stdout


def sha256_at(rev, path):
    return hashlib.sha256(git_bytes("show", "{}:{}".format(rev,
                                                           path))).hexdigest()


def parse_dockerfile(text):
    base = re.search(r"^FROM\s+(\S+)", text, re.M).group(1)
    remote = re.search(r"git remote add origin (\S+)", text).group(1)
    pin = re.search(r"git fetch -q --depth=1 origin ([0-9a-f]{40})",
                    text).group(1)
    script = re.search(r"bash (get_code_packages\S*\.sh)", text).group(1)
    pip = re.findall(r"^\s+([A-Za-z0-9_.-]+)==([0-9][^\s\\]*)", text, re.M)
    return base, remote, pin, script, pip


def parse_fetch_script(text):
    """Return (components, patches, extras) from the pinned bootstrap."""
    # join backslash continuations so each clone is one logical line
    flat = re.sub(r"\\\n\s*", " ", text)
    components = []
    for kind, args in re.findall(
            r"^clone_repo_at_(commit|tag)\s+(.+)$", flat, re.M):
        a = args.split()
        url = re.sub(r"//[^/@]+@", "//", a[0])  # drop a user@ in the URL
        entry = {"directory": a[1], "repository": url}
        if kind == "commit":
            entry["commit"] = a[2]
            if len(a) > 3:
                entry["cloned_from_branch"] = a[3]
        else:
            entry["tag"] = a[2]
        components.append(entry)
    # ( cd <dir> ; patch -p1 --forward < ../patches/<file> )
    patches = re.findall(
        r"cd (\S+_code)\s*\n\s*patch -p1 --forward < \.\./patches/(\S+)",
        text)
    extras = {}
    m = re.search(r'PYTHIA_REPO="([^"]+)"', text)
    c = re.search(r'PYTHIA_COMMIT="([0-9a-f]+)"', text)
    if m and c:
        extras["pythia8"] = {"repository": m.group(1), "commit": c.group(1)}
    return components, patches, extras


def tracked_overlays(rev):
    """Files the framework tracks inside a fetched code directory.

    The bootstrap deletes each <name>_code directory before cloning, so such a
    file only reaches the image if the script explicitly restores it.
    """
    out = []
    for line in git("ls-tree", "-r", rev, "codes").splitlines():
        meta, path = line.split("\t")
        if re.match(r"codes/[^/]+_code/", path):
            out.append((path, meta.split()[2]))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dockerfile-commit", required=True)
    args = ap.parse_args()

    df_commit = git("rev-parse", args.dockerfile_commit).strip()
    dockerfile = git("show", df_commit + ":docker/Dockerfile")
    base, remote, pin, script, pip = parse_dockerfile(dockerfile)
    script_path = "codes/" + script
    fetch = git("show", "{}:{}".format(pin, script_path))
    components, patches, extras = parse_fetch_script(fetch)
    patch_of = {}
    for directory, name in patches:
        patch_of.setdefault(directory, []).append(name)
    restored = set(
        re.findall(r'cp "\$\{[A-Z_]+\}" (\S+_code/\S+)', fetch))

    w = sys.stdout.write
    w("# Generated by scripts/campaign_lock.py --dockerfile-commit {}\n".
      format(df_commit[:7]))
    w("# Do not edit: regenerate.  Every value is read out of git.\n")
    w("image_recipe:\n")
    w("  dockerfile_commit: {}\n".format(df_commit))
    w("  dockerfile_sha256: {}\n".format(
        sha256_at(df_commit, "docker/Dockerfile")))
    w("  base_image: {}\n".format(base))
    snapshot = re.search(r"vault\.almalinux\.org/([0-9.]+)/", dockerfile)
    if snapshot:
        w("  system_packages: frozen snapshot (AlmaLinux {0} vault, EPEL {0} archive)\n"
          .format(snapshot.group(1)))
    else:
        w("  # yum packages are NOT pinned by the recipe: a rebuild takes whatever\n"
          "  # the base image's repositories serve that day.  The image file (md5 in\n"
          "  # campaign.yaml) is therefore the only exact artefact.\n")
    w("  python_packages:\n")
    for name, version in pip:
        w("    {}: \"{}\"\n".format(name, version))
    w("framework:\n")
    w("  repository: {}\n".format(remote))
    w("  commit: {}\n".format(pin))
    w("  bootstrap: {}\n".format(script_path))
    w("  bootstrap_sha256: {}\n".format(sha256_at(pin, script_path)))
    w("components:\n")
    for c in components:
        w("  - directory: codes/{}\n".format(c["directory"]))
        w("    repository: {}\n".format(c["repository"]))
        for key in ("commit", "tag", "cloned_from_branch"):
            if key in c:
                w("    {}: {}\n".format(key, c[key]))
        for name in patch_of.get(c["directory"], []):
            path = "codes/patches/" + name
            w("    patch:\n")
            w("      file: {}\n".format(path))
            w("      sha256: {}\n".format(sha256_at(pin, path)))
        over = [(p, blob) for p, blob in tracked_overlays(pin)
                if p.startswith("codes/" + c["directory"] + "/")]
        for path, blob in over:
            rel = path[len("codes/"):]
            w("    framework_file:\n")
            w("      file: {}\n".format(path))
            w("      git_blob: {}\n".format(blob))
            w("      in_image: {}\n".format(
                "true   # restored over the clone by the bootstrap"
                if rel in restored else
                "false  # deleted by the bootstrap's clone, never restored"))
    for name, e in extras.items():
        w("  - directory: (built from source, not kept)  # {}\n".format(name))
        w("    repository: {}\n".format(e["repository"]))
        w("    commit: {}\n".format(e["commit"]))


if __name__ == "__main__":
    main()
